-- Apteka Order Manager – база данни в Supabase.
-- Поставя се ВЕДНЪЖ в Supabase → SQL Editor → Run.
-- Безопасно е да се пусне и повторно (при обновяване) – не трие данни.
--
-- Сигурност: никой не пише директно в таблиците. Всяка промяна минава през
-- функциите долу, които проверяват ролята (главен / помощник / служител).
-- Само „главен“ мести заявките – точно като в старата версия.
-- Нов потребител не вижда нищо, докато Главният не го одобри.

-- ---------- Таблици ----------
-- Потребители: всеки си прави име и парола сам; Главният го одобрява и му дава роля.
-- role = null → чака одобрение (не вижда нищо).
create table if not exists public.app_users (
  user_id    uuid primary key references auth.users(id) on delete cascade,
  name       text not null,
  role       text check (role in ('glaven', 'pomoshtnik', 'sluzhitel')),
  created_at timestamptz not null default now()
);

create table if not exists public.requests (
  id          bigint generated by default as identity primary key,
  date        text not null,
  patient     text not null,
  phone       text not null default '',
  medicine    text not null,
  qty         text not null default '',
  note        text not null default '',
  status      text not null default 'new' check (status in ('new', 'ordered', 'arrived', 'done', 'unavailable')),
  expected    text not null default '',
  nzok_code   text not null default '',
  nzok_name   text not null default '',
  nzok_qty    text not null default '',
  nzok_note   text not null default '',
  created_by  text not null default '',
  created_at  timestamptz not null default now(),
  updated_by  text not null default '',
  updated_at  timestamptz not null default now()
);

create table if not exists public.history (
  id          bigint generated by default as identity primary key,
  request_id  bigint not null references public.requests(id) on delete cascade,
  status      text not null,
  comment     text not null default '',
  by          text not null default '',
  at          timestamptz not null default now()
);
create index if not exists idx_history_req on public.history(request_id);

-- Заявка + последният коментар (за картите на таблото).
create or replace view public.requests_v with (security_invoker = true) as
  select r.*, (select h.comment from public.history h
               where h.request_id = r.id and h.comment <> '' and h.by <> ''
               order by h.id desc limit 1) as last_comment
  from public.requests r;

-- ---------- Права ----------
alter table public.app_users enable row level security;
alter table public.requests  enable row level security;
alter table public.history   enable row level security;

create or replace function public.my_role() returns text
  language sql stable security definer set search_path = public as
$$ select role from public.app_users where user_id = auth.uid() $$;
create or replace function public.my_name() returns text
  language sql stable security definer set search_path = public as
$$ select name from public.app_users where user_id = auth.uid() $$;

drop policy if exists "read users" on public.app_users;
create policy "read users" on public.app_users for select to authenticated
  using (user_id = auth.uid() or public.my_role() = 'glaven');
drop policy if exists "pharmacy reads requests" on public.requests;
create policy "pharmacy reads requests" on public.requests for select to authenticated using (public.my_role() is not null);
drop policy if exists "pharmacy reads history" on public.history;
create policy "pharmacy reads history" on public.history for select to authenticated using (public.my_role() is not null);

revoke all on public.app_users, public.requests, public.history, public.requests_v from anon, authenticated;
grant select on public.app_users, public.requests, public.history, public.requests_v to authenticated;

-- Нов потребител (от бутона „Нов потребител“) → ред в app_users.
-- Най-първият потребител става Главен автоматично; всички следващи чакат одобрение.
create or replace function public._on_new_user() returns trigger
  language plpgsql security definer set search_path = public as
$$
begin
  insert into public.app_users (user_id, name, role)
  values (new.id, left(btrim(coalesce(new.raw_user_meta_data->>'name', new.email)), 40),
          case when not exists (select 1 from public.app_users where role = 'glaven') then 'glaven' end);
  return new;
end $$;
drop trigger if exists apteka_on_new_user on auth.users;
create trigger apteka_on_new_user after insert on auth.users for each row execute function public._on_new_user();

-- Главният одобрява / сменя роля / премахва.
create or replace function public.set_user_role(p_user uuid, p_role text) returns void
  language plpgsql security definer set search_path = public as
$$
begin
  if my_role() is distinct from 'glaven' then raise exception 'Само главният управлява потребителите.'; end if;
  if p_role is not null and p_role not in ('glaven', 'pomoshtnik', 'sluzhitel') then raise exception 'Невалидна роля.'; end if;
  if coalesce(p_role, '') <> 'glaven' and (select role from app_users where user_id = p_user) = 'glaven'
     and (select count(*) from app_users where role = 'glaven') = 1 then
    raise exception 'Трябва да остане поне един Главен.';
  end if;
  update app_users set role = p_role where user_id = p_user;
end $$;

create or replace function public.remove_user(p_user uuid) returns void
  language plpgsql security definer set search_path = public as
$$
begin
  if my_role() is distinct from 'glaven' then raise exception 'Само главният управлява потребителите.'; end if;
  if p_user = auth.uid() then raise exception 'Не можете да премахнете себе си.'; end if;
  delete from app_users where user_id = p_user;
  begin
    delete from auth.users where id = p_user; -- освобождава името за нова регистрация
  exception when others then null;
  end;
end $$;

-- Живи известия (новите заявки излизат веднага на всички компютри).
do $$ begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and tablename = 'requests') then
    alter publication supabase_realtime add table public.requests;
  end if;
end $$;

-- ---------- Помощни ----------
create or replace function public._clean(v text, max_len int) returns text
  language sql immutable as $$ select left(btrim(coalesce(v, '')), max_len) $$;
create or replace function public._is_date(v text) returns boolean
  language sql immutable as $$ select coalesce(v, '') ~ '^\d{4}-\d{2}-\d{2}$' $$;
create or replace function public._bg_date(v text) returns text
  language sql immutable as
$$ select case when public._is_date(v) then substr(v, 9, 2) || '.' || substr(v, 6, 2) || '.' || substr(v, 1, 4) else coalesce(v, '') end $$;
create or replace function public._today() returns text
  language sql stable as $$ select to_char(now() at time zone 'Europe/Sofia', 'YYYY-MM-DD') $$;
create or replace function public._row(p_id bigint) returns jsonb
  language sql stable security definer set search_path = public as
$$ select to_jsonb(v) from public.requests_v v where v.id = p_id $$;

-- ---------- Нова заявка (всички роли) ----------
create or replace function public.create_request(p jsonb) returns jsonb
  language plpgsql security definer set search_path = public as
$$
declare
  v_by text := my_name();
  v_patient text := _clean(p->>'patient', 120);
  v_medicine text := _clean(p->>'medicine', 300);
  v_id bigint;
begin
  if my_role() is null then raise exception 'Нямате достъп.'; end if;
  if v_patient = '' or v_medicine = '' then raise exception 'Попълнете пациент и лекарство.'; end if;
  if v_by is null then raise exception 'Нямате достъп.'; end if;
  insert into requests (date, patient, phone, medicine, qty, note, nzok_code, nzok_name, nzok_qty, nzok_note, created_by, updated_by)
  values (case when _is_date(p->>'date') then p->>'date' else _today() end, v_patient, _clean(p->>'phone', 40),
          v_medicine, _clean(p->>'qty', 40), _clean(p->>'note', 500),
          _clean(p->>'nzok_code', 60), _clean(p->>'nzok_name', 200), _clean(p->>'nzok_qty', 40), _clean(p->>'nzok_note', 500),
          v_by, v_by)
  returning id into v_id;
  insert into history (request_id, status, comment, by) values (v_id, 'new', 'Заявката е създадена', '');
  return _row(v_id);
end $$;

-- ---------- Статус / доставка / коментар ----------
-- Статуса и датата на доставка ги сменя САМО главният. Коментар може всеки.
create or replace function public.set_status(p_id bigint, p jsonb) returns jsonb
  language plpgsql security definer set search_path = public as
$$
declare
  r requests;
  v_by text := my_name();
  v_status text;
  v_expected text;
  v_comment text := _clean(p->>'comment', 500);
  v_note text;
  v_changes boolean;
begin
  if my_role() is null then raise exception 'Нямате достъп.'; end if;
  select * into r from requests where id = p_id for update;
  if not found then raise exception 'Няма такава заявка.'; end if;
  v_status := coalesce(nullif(p->>'status', ''), r.status);
  v_expected := case when not (p ? 'expected') then r.expected
                     when _is_date(p->>'expected') then p->>'expected' else '' end;
  if v_status not in ('new', 'ordered', 'arrived', 'done', 'unavailable') then raise exception 'Невалиден статус.'; end if;
  if v_by is null then raise exception 'Нямате достъп.'; end if;
  v_changes := v_status <> r.status or v_expected <> r.expected;
  if not v_changes and v_comment = '' then raise exception 'Няма промяна.'; end if;
  if v_changes and my_role() <> 'glaven' then
    raise exception 'Статуса и датата ги сменя само поръчващият. Можете да добавите коментар.';
  end if;
  if v_expected <> r.expected then
    v_note := case when v_expected <> '' then 'Очаква се на ' || _bg_date(v_expected) else 'Датата на доставка е премахната' end;
    v_comment := case when v_comment <> '' then v_comment || ' · ' || v_note else v_note end;
  end if;
  update requests set status = v_status, expected = v_expected, updated_by = v_by, updated_at = now() where id = p_id;
  insert into history (request_id, status, comment, by) values (p_id, v_status, v_comment, v_by);
  return _row(p_id);
end $$;

-- ---------- Редакция (всички роли), с история какво е сменено ----------
create or replace function public.edit_request(p_id bigint, p jsonb) returns jsonb
  language plpgsql security definer set search_path = public as
$$
declare
  r requests;
  n requests;
  v_by text := my_name();
  ch text[] := '{}';
begin
  if my_role() is null then raise exception 'Нямате достъп.'; end if;
  select * into r from requests where id = p_id for update;
  if not found then raise exception 'Няма такава заявка.'; end if;
  if v_by is null then raise exception 'Нямате достъп.'; end if;
  n := r;
  n.patient := _clean(p->>'patient', 120);
  n.medicine := _clean(p->>'medicine', 300);
  if n.patient = '' or n.medicine = '' then raise exception 'Попълнете пациент и лекарство.'; end if;
  n.date := case when _is_date(p->>'date') then p->>'date' else r.date end;
  n.phone := _clean(p->>'phone', 40);
  n.qty := _clean(p->>'qty', 40);
  n.note := _clean(p->>'note', 500);
  n.nzok_code := _clean(p->>'nzok_code', 60);
  n.nzok_name := _clean(p->>'nzok_name', 200);
  n.nzok_qty := _clean(p->>'nzok_qty', 40);
  n.nzok_note := _clean(p->>'nzok_note', 500);

  if r.date <> n.date then ch := ch || format('Дата: „%s“ → „%s“', _bg_date(r.date), _bg_date(n.date)); end if;
  if r.patient <> n.patient then ch := ch || format('Пациент: „%s“ → „%s“', coalesce(nullif(r.patient, ''), '—'), coalesce(nullif(n.patient, ''), '—')); end if;
  if r.phone <> n.phone then ch := ch || format('Телефон: „%s“ → „%s“', coalesce(nullif(r.phone, ''), '—'), coalesce(nullif(n.phone, ''), '—')); end if;
  if r.medicine <> n.medicine then ch := ch || format('Лекарство: „%s“ → „%s“', coalesce(nullif(r.medicine, ''), '—'), coalesce(nullif(n.medicine, ''), '—')); end if;
  if r.qty <> n.qty then ch := ch || format('Количество: „%s“ → „%s“', coalesce(nullif(r.qty, ''), '—'), coalesce(nullif(n.qty, ''), '—')); end if;
  if r.note <> n.note then ch := ch || format('Бележка: „%s“ → „%s“', coalesce(nullif(r.note, ''), '—'), coalesce(nullif(n.note, ''), '—')); end if;
  if r.nzok_code <> n.nzok_code then ch := ch || format('НЗОК код: „%s“ → „%s“', coalesce(nullif(r.nzok_code, ''), '—'), coalesce(nullif(n.nzok_code, ''), '—')); end if;
  if r.nzok_name <> n.nzok_name then ch := ch || format('НЗОК МНН: „%s“ → „%s“', coalesce(nullif(r.nzok_name, ''), '—'), coalesce(nullif(n.nzok_name, ''), '—')); end if;
  if r.nzok_qty <> n.nzok_qty then ch := ch || format('НЗОК количество: „%s“ → „%s“', coalesce(nullif(r.nzok_qty, ''), '—'), coalesce(nullif(n.nzok_qty, ''), '—')); end if;
  if r.nzok_note <> n.nzok_note then ch := ch || format('НЗОК бележка: „%s“ → „%s“', coalesce(nullif(r.nzok_note, ''), '—'), coalesce(nullif(n.nzok_note, ''), '—')); end if;
  if cardinality(ch) = 0 then raise exception 'Няма промяна.'; end if;

  update requests set date = n.date, patient = n.patient, phone = n.phone, medicine = n.medicine, qty = n.qty, note = n.note,
    nzok_code = n.nzok_code, nzok_name = n.nzok_name, nzok_qty = n.nzok_qty, nzok_note = n.nzok_note,
    updated_by = v_by, updated_at = now()
  where id = p_id;
  insert into history (request_id, status, comment, by) values (p_id, r.status, 'Редакция – ' || array_to_string(ch, '; '), v_by);
  return _row(p_id);
end $$;

-- ---------- Пренасяне на старите данни (само главният) ----------
-- Запазва старите номера (№). Пуснато повторно – пропуска вече пренесените.
create or replace function public.import_legacy(p jsonb) returns int
  language plpgsql security definer set search_path = public as
$$
declare
  x jsonb;
  h jsonb;
  added int := 0;
begin
  if my_role() is distinct from 'glaven' then raise exception 'Само главният може да пренася данни.'; end if;
  for x in select * from jsonb_array_elements(p) loop
    if exists (select 1 from requests where id = (x->>'id')::bigint) then continue; end if;
    insert into requests (id, date, patient, phone, medicine, qty, note, status, expected,
                          nzok_code, nzok_name, nzok_qty, nzok_note, created_by, created_at, updated_by, updated_at)
    overriding system value
    values ((x->>'id')::bigint, x->>'date', x->>'patient', coalesce(x->>'phone', ''), x->>'medicine',
            coalesce(x->>'qty', ''), coalesce(x->>'note', ''), x->>'status', coalesce(x->>'expected', ''),
            coalesce(x->>'nzok_code', ''), coalesce(x->>'nzok_name', ''), coalesce(x->>'nzok_qty', ''), coalesce(x->>'nzok_note', ''),
            coalesce(x->>'created_by', ''), (x->>'created_at')::timestamptz,
            coalesce(x->>'updated_by', ''), (x->>'updated_at')::timestamptz);
    for h in select * from jsonb_array_elements(coalesce(x->'history', '[]')) loop
      insert into history (request_id, status, comment, by, at)
      values ((x->>'id')::bigint, h->>'status', coalesce(h->>'comment', ''), coalesce(h->>'by', ''), (h->>'at')::timestamptz);
    end loop;
    added := added + 1;
  end loop;
  -- Новите заявки продължават номерацията след старите.
  perform setval(pg_get_serial_sequence('public.requests', 'id'), greatest((select max(id) from requests), 1));
  return added;
end $$;

revoke all on function public.my_role(), public.my_name(), public.create_request(jsonb), public.set_status(bigint, jsonb),
  public.edit_request(bigint, jsonb), public.import_legacy(jsonb), public._row(bigint),
  public.set_user_role(uuid, text), public.remove_user(uuid), public._on_new_user() from public, anon, authenticated;
grant execute on function public.my_role(), public.my_name(), public.create_request(jsonb), public.set_status(bigint, jsonb),
  public.edit_request(bigint, jsonb), public.import_legacy(jsonb), public.set_user_role(uuid, text), public.remove_user(uuid)
  to authenticated;
